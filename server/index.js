
import 'dotenv/config'
import express from 'express'
import mongoose from 'mongoose'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const app = express()

const port = Number(process.env.PORT || 4000)
const host = process.env.HOST || '127.0.0.1'
const mongoUri =
  process.env.MONGODB_URI ||
  'mongodb://127.0.0.1:27017/somsat_mission_ops'

const ollamaUrl = (
  process.env.OLLAMA_URL || 'http://127.0.0.1:11434'
).replace(/\/+$/, '')

const ollamaModel = process.env.OLLAMA_MODEL || 'llama3.2'

const currentDir = path.dirname(fileURLToPath(import.meta.url))
const clientBuild = path.resolve(currentDir, '../dist')

app.use(express.json({ limit: '16kb' }))

// --------------------------------------------------
// MONGODB SCHEMA
// --------------------------------------------------

const missionEventSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
      maxlength: 90,
    },

    type: {
      type: String,
      required: true,
      enum: [
        'Deployment',
        'Telemetry',
        'Communications',
        'AI decision',
        'Operations',
      ],
    },

    priority: {
      type: String,
      required: true,
      enum: ['Low', 'Normal', 'High', 'Critical'],
      default: 'Normal',
    },

    status: {
      type: String,
      required: true,
      enum: ['Monitoring', 'Active', 'Resolved'],
      default: 'Monitoring',
    },

    description: {
      type: String,
      required: true,
      trim: true,
      maxlength: 500,
    },

    // Solution generated by Ollama / Llama 3.2
    solution: {
      type: String,
      default: '',
      maxlength: 5000,
    },

    eventTime: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
    collection: 'mission_events',
  }
)

const MissionEvent = mongoose.model(
  'MissionEvent',
  missionEventSchema
)

// --------------------------------------------------
// HELPER FUNCTIONS
// --------------------------------------------------

function databaseReady(_request, response, next) {
  if (mongoose.connection.readyState !== 1) {
    return response.status(503).json({
      message:
        'MongoDB is not connected. Start MongoDB and try again.',
    })
  }

  return next()
}

function eventFields(body) {
  if (
    !body ||
    typeof body !== 'object' ||
    Array.isArray(body)
  ) {
    return {}
  }

  const fields = [
    'title',
    'type',
    'priority',
    'status',
    'description',
    'solution',
  ]

  return Object.fromEntries(
    fields
      .filter((field) => Object.hasOwn(body, field))
      .map((field) => [field, body[field]])
  )
}

function sendRouteError(response, error) {
  if (error.name === 'ValidationError') {
    const message = Object.values(error.errors)
      .map((entry) => entry.message)
      .join(' ')

    return response.status(400).json({ message })
  }

  if (error.name === 'CastError') {
    return response.status(400).json({
      message: 'Invalid mission event identifier.',
    })
  }

  console.error('Mission event request failed:', error.message)

  return response.status(500).json({
    message: 'The mission records request failed.',
  })
}

// --------------------------------------------------
// HEALTH CHECK
// --------------------------------------------------

app.get('/api/health', (_request, response) => {
  response.json({
    status: 'ok',
    database:
      mongoose.connection.readyState === 1
        ? 'connected'
        : 'disconnected',
    ollamaModel,
  })
})

// --------------------------------------------------
// OLLAMA: GENERATE EVENT SOLUTION
// --------------------------------------------------

app.post('/api/generate-solution', async (request, response) => {
  const { title, type, priority, status } = request.body || {}

  const validInputs = [title, type, priority, status].every(
    (value) =>
      typeof value === 'string' && value.trim().length > 0
  )

  if (!validInputs) {
    return response.status(400).json({
      message:
        'Please provide the event title, type, priority, and status.',
    })
  }

  const cleanTitle = title.trim().slice(0, 90)
  const cleanType = type.trim()
  const cleanPriority = priority.trim()
  const cleanStatus = status.trim()

  const allowedTypes = [
    'Deployment',
    'Telemetry',
    'Communications',
    'AI decision',
    'Operations',
  ]

  const allowedPriorities = [
    'Low',
    'Normal',
    'High',
    'Critical',
  ]

  const allowedStatuses = [
    'Monitoring',
    'Active',
    'Resolved',
  ]

  if (
    !allowedTypes.includes(cleanType) ||
    !allowedPriorities.includes(cleanPriority) ||
    !allowedStatuses.includes(cleanStatus)
  ) {
    return response.status(400).json({
      message: 'Invalid event type, priority, or status.',
    })
  }

  const prompt = `
You are a mission operations assistant for a satellite monitoring dashboard.

EVENT DETAILS
Title: ${cleanTitle}
Type: ${cleanType}
Priority: ${cleanPriority}
Current status: ${cleanStatus}

TASK
Recommend a practical response to this event.

RULES
1. Give 3 to 5 numbered steps.
2. Tailor recommendations to the event title and type.
3. Consider its priority and current status.
4. Do not invent telemetry readings, confirmed causes, or facts.
5. Distinguish recommended actions from verified facts.
6. Require qualified operator approval for safety-critical actions.
7. If the event is Resolved, recommend verification and prevention steps.
8. Do not claim that any action has already been performed.
9. Return only the recommended solution in clear, concise language.
`

  try {
    const ollamaResponse = await fetch(
      `${ollamaUrl}/api/generate`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model: ollamaModel,
          prompt,
          stream: false,
          options: {
            temperature: 0.3,
          },
        }),
        signal: AbortSignal.timeout(120000),
      }
    )

    const data = await ollamaResponse.json()

    if (!ollamaResponse.ok) {
      console.error('Ollama returned an error:', data.error)

      return response.status(502).json({
        message:
          data.error || 'Ollama failed to generate a solution.',
      })
    }

    const solution = data.response?.trim()

    if (!solution) {
      return response.status(502).json({
        message: 'Ollama returned an empty solution.',
      })
    }

    return response.json({
      solution: solution.slice(0, 5000),
      model: ollamaModel,
    })
  } catch (error) {
    console.error(
      'Ollama solution generation error:',
      error.message
    )

    const timeout = error.name === 'TimeoutError'

    return response.status(503).json({
      message: timeout
        ? 'Ollama took too long to respond. Please try again.'
        : 'Cannot connect to Ollama. Ensure Ollama is running and the model is installed.',
    })
  }
})

// --------------------------------------------------
// GET ALL MISSION EVENTS
// --------------------------------------------------

app.get('/api/events', databaseReady, async (_request, response) => {
  try {
    const events = await MissionEvent.find()
      .sort({ eventTime: -1, createdAt: -1 })
      .lean()

    return response.json({ events })
  } catch (error) {
    return sendRouteError(response, error)
  }
})

// --------------------------------------------------
// CREATE A MISSION EVENT
// --------------------------------------------------

app.post('/api/events', databaseReady, async (request, response) => {
  try {
    const event = await MissionEvent.create(
      eventFields(request.body)
    )

    return response.status(201).json({ event })
  } catch (error) {
    return sendRouteError(response, error)
  }
})

// --------------------------------------------------
// GET ONE MISSION EVENT
// --------------------------------------------------

app.get('/api/events/:id', databaseReady, async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.id)) {
    return response.status(400).json({
      message: 'Invalid mission event identifier.',
    })
  }

  try {
    const event = await MissionEvent.findById(
      request.params.id
    ).lean()

    if (!event) {
      return response.status(404).json({
        message: 'Mission event not found.',
      })
    }

    return response.json({ event })
  } catch (error) {
    return sendRouteError(response, error)
  }
})

// --------------------------------------------------
// UPDATE A MISSION EVENT
// --------------------------------------------------

app.patch('/api/events/:id', databaseReady, async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.id)) {
    return response.status(400).json({
      message: 'Invalid mission event identifier.',
    })
  }

  const updates = eventFields(request.body)

  if (Object.keys(updates).length === 0) {
    return response.status(400).json({
      message: 'Provide at least one event field to update.',
    })
  }

  try {
    const event = await MissionEvent.findByIdAndUpdate(
      request.params.id,
      updates,
      {
        returnDocument: 'after',
        runValidators: true,
      }
    )

    if (!event) {
      return response.status(404).json({
        message: 'Mission event not found.',
      })
    }

    return response.json({ event })
  } catch (error) {
    return sendRouteError(response, error)
  }
})

// --------------------------------------------------
// DELETE A MISSION EVENT
// --------------------------------------------------

app.delete('/api/events/:id', databaseReady, async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.id)) {
    return response.status(400).json({
      message: 'Invalid mission event identifier.',
    })
  }

  try {
    const event = await MissionEvent.findByIdAndDelete(
      request.params.id
    )

    if (!event) {
      return response.status(404).json({
        message: 'Mission event not found.',
      })
    }

    return response.json({
      message: 'Mission event deleted.',
      id: event.id,
    })
  } catch (error) {
    return sendRouteError(response, error)
  }
})

// --------------------------------------------------
// API 404 HANDLER
// Keep this AFTER all API routes.
// --------------------------------------------------

app.use('/api', (_request, response) => {
  return response.status(404).json({
    message: 'API endpoint not found.',
  })
})

// --------------------------------------------------
// SERVE FRONTEND BUILD
// --------------------------------------------------

app.use(express.static(clientBuild))

app.use((request, response, next) => {
  if (request.method !== 'GET') {
    return next()
  }

  response.sendFile(
    path.join(clientBuild, 'index.html'),
    (error) => {
      if (error && !response.headersSent) {
        next(error)
      }
    }
  )
})

// --------------------------------------------------
// GLOBAL ERROR HANDLER
// --------------------------------------------------

app.use((error, _request, response, _next) => {
  if (error instanceof SyntaxError && 'body' in error) {
    return response.status(400).json({
      message: 'Request body must be valid JSON.',
    })
  }

  console.error('Unhandled server error:', error.message)

  if (response.headersSent) {
    return
  }

  return response.status(500).json({
    message: 'Internal server error.',
  })
})

// --------------------------------------------------
// START SERVER AND CONNECT DATABASE
// --------------------------------------------------

async function startServer() {
  try {
    await mongoose.connect(mongoUri)
    console.log('Connected to MongoDB')
  } catch (error) {
    console.error(
      `MongoDB connection failed: ${error.message}`
    )
  }

  app.listen(port, host, () => {
    console.log(
      `SomSat API listening on http://${host}:${port}`
    )
    console.log(`Ollama model configured: ${ollamaModel}`)
  })
}

startServer()
